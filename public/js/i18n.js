const LANG_KEY = 'y6_lang';

export function getLang() {
  try { return localStorage.getItem(LANG_KEY) === 'ms' ? 'ms' : 'en'; } catch { return 'en'; }
}

export function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang === 'ms' ? 'ms' : 'en'); } catch { /* private mode */ }
}

export function t(key, params) {
  const lang = getLang();
  let s = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll('{' + k + '}', String(v));
  }
  return s;
}

export function tServer(message) {
  if (getLang() !== 'ms') return message;
  return SERVER_MS[message] || message;
}

export function topicName(topic) {
  if (getLang() !== 'ms') return topic;
  return TOPIC_MS[topic] || topic;
}

// Wire up static HTML: <span data-i18n="key">, data-i18n-placeholder, data-i18n-title.
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((n) => { n.placeholder = t(n.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach((n) => { n.title = t(n.dataset.i18nTitle); });
}

// EN | BM switch. Toggling reloads the page — every view then renders in the
// chosen language, including data fetched from the server.
export function langToggle() {
  const wrap = document.createElement('div');
  wrap.className = 'langswitch';
  wrap.setAttribute('role', 'group');
  wrap.setAttribute('aria-label', 'Language / Bahasa');
  for (const [code, label] of [['en', 'EN'], ['ms', 'BM']]) {
    const b = document.createElement('button');
    b.type = 'button';
    b.textContent = label;
    if (getLang() === code) b.classList.add('on');
    b.addEventListener('click', () => {
      if (getLang() !== code) { setLang(code); location.reload(); }
    });
    wrap.append(b);
  }
  return wrap;
}
